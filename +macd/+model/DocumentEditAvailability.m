classdef DocumentEditAvailability
    % DocumentEditAvailability Check declared subtree conditions without rehearsing commands.
    %   Queries inspect source ownership, hierarchy and placement only. They never
    %   clone a document, generate candidate source or edit history. Actual commands
    %   validate their chosen edit atomically before publishing it.
    methods (Static)
        function state = deletion(document, id, registry)
            % deletion Check owned source and subtree links without deleting a candidate.
            arguments (Input)
                document (1, 1) macd.model.DocumentModel
                id (1, 1) string
                registry (1, 1) macd.model.ComponentRegistry
            end
            arguments (Output)
                state (1, 1) struct
            end
            state = struct("Enabled", false, "Reason", "");
            try
                snapshot = macd.model.DocumentEditAvailability.inspect(document, id);
                for record = snapshot.Records
                    callbacks = macd.source.CallbackSourceAnalyzer.analyze(document, record.Id, registry);
                    if any(string({callbacks.State}) ~= "absent")
                        error("macd:DocumentEditAvailability:Callbacks", "Callback ownership prevents complete subtree deletion.");
                    end
                end
                % Retain references generated by the editor while leaving arbitrary logic untouched.
                ids = string({snapshot.Records.Id});
                for owner = document.Components
                    if any(ids == owner.Id), continue, end
                    for entry = owner.Properties
                        if isfield(entry.Metadata, "SubtreeReferenceId") && any(ids == string(entry.Metadata.SubtreeReferenceId))
                            error("macd:DocumentEditAvailability:Reference", "An editor-owned reference still targets this subtree.");
                        end
                    end
                end
                removed = document.Components(ismember(string({document.Components.Id}), ids));
                references = macd.source.SubtreeSourceEdits.detachedParentReferences(document, ids);
                macd.source.SubtreeSourceEdits.deletion(document.OriginalText, removed, references);
                state.Enabled = true;
            catch exception
                state.Reason = string(exception.message);
            end
        end

        function state = copying(document, id, registry)
            % copying Check transferable values and ownership without evaluating a copied document.
            arguments (Input)
                document (1, 1) macd.model.DocumentModel
                id (1, 1) string
                registry (1, 1) macd.model.ComponentRegistry
            end
            arguments (Output)
                state (1, 1) struct
            end
            state = struct("Enabled", false, "Reason", "");
            try
                if id == document.RootComponentId
                    error("macd:DocumentEditAvailability:Root", "The document root cannot be copied.");
                end
                snapshot = macd.model.DocumentEditAvailability.inspect(document, id);
                macd.model.DocumentEditAvailability.ownership(document, snapshot);
                for record = snapshot.Records
                    definition = registry.get(record.Factory, record.CreationArguments);
                    if definition.IsProgrammaticOnly || definition.Category == "FigureTools"
                        error("macd:DocumentEditAvailability:Factory", "This construction family is not supported for copying.");
                    end
                    callbacks = macd.source.CallbackSourceAnalyzer.analyze(document, record.Id, registry);
                    if any(string({callbacks.State}) ~= "absent")
                        error("macd:DocumentEditAvailability:Callbacks", "Callback bindings cannot yet be duplicated safely.");
                    end
                    for entry = record.Properties
                        if entry.ValueKind == "expression"
                            owner = document.getComponent(record.Id);
                            if isfield(entry.Metadata, "SubtreeReferenceId")
                                target = document.getComponent(string(entry.Metadata.SubtreeReferenceId));
                                if isempty(target)
                                    error("macd:DocumentEditAvailability:Reference", "Reference target is missing.");
                                end
                                macd.model.SubtreeReferencePolicy.validate(document, owner, entry.Path, target, registry);
                            else
                                macd.model.SubtreeReferencePolicy.resolve(document, owner, entry.Path, entry.SourceExpression, registry);
                            end
                        elseif entry.ValueKind ~= "literal" || registry.isReadOnlyProperty(record.Factory, entry.Path, record.CreationArguments)
                            error("macd:DocumentEditAvailability:Value", "A property cannot be copied without losing source behavior.");
                        else
                            macd.source.LiteralEncoder.encode(entry.LiteralValue);
                        end
                    end
                    if any(arrayfun(@(item) item.ComponentId == record.Id && item.Code == "source-creation-property", document.Diagnostics))
                        error("macd:DocumentEditAvailability:Constructor", "The constructor contains preserved unsupported properties.");
                    end
                end
                state.Enabled = true;
            catch exception
                state.Reason = string(exception.message);
            end
        end

        function states = reparenting(document, id, registry, measuredPosition)
            % reparenting Inspect all destinations using one subtree and side-effect-free placement rules.
            arguments (Input)
                document (1, 1) macd.model.DocumentModel
                id (1, 1) string
                registry (1, 1) macd.model.ComponentRegistry
                measuredPosition double {mustBeFinite} = []
            end
            arguments (Output)
                states struct
            end
            states = struct("Id", {}, "Name", {}, "Enabled", {}, "Reason", {});
            source = document.getComponent(id);
            reason = "";
            snapshot = macd.model.SubtreeSnapshot.empty;
            try
                snapshot = macd.model.DocumentEditAvailability.inspect(document, id);
                macd.model.DocumentEditAvailability.ownership(document, snapshot, true);
                if macd.model.PropertyStateResolver.hasUnresolvedExecution(document)
                    error("macd:DocumentEditAvailability:UnknownHierarchy", "Unresolved initialization effects prevent proving subtree relocation safety.");
                end
            catch exception
                reason = string(exception.message);
            end
            % Collect the finite incoming reference constraints once for all destinations.
            requiredParents = strings(1, 0);
            if strlength(reason) == 0
                definition = registry.get(source.Factory, source.CreationArguments);
                for owner = document.Components
                    entry = owner.getProperty("SelectedTab");
                    if ~isempty(entry) && isfield(entry.Metadata, "SubtreeReferenceId") && ...
                            string(entry.Metadata.SubtreeReferenceId) == id
                        requiredParents(end + 1) = owner.Id; %#ok<AGROW>
                    end
                end
            end
            for parent = document.Components
                state = struct("Id", parent.Id, "Name", parent.Name, "Enabled", false, "Reason", reason);
                if strlength(reason) == 0
                    if source.ParentId == parent.Id
                        state.Reason = "Current parent.";
                    elseif ~any(definition.AllowedParentFactories == parent.Factory)
                        state.Reason = "This component type cannot use that parent.";
                    elseif any(requiredParents ~= parent.Id)
                        state.Reason = "An editor-owned SelectedTab reference requires its current tab group.";
                    else
                        try
                            macd.model.SubtreePlacementPlanner.prepare(document, snapshot, parent.Id, registry, ...
                                string({snapshot.Records.Id}), measuredPosition);
                            state.Enabled = true;
                        catch exception
                            state.Reason = string(exception.message);
                        end
                    end
                end
                states(end + 1) = state; %#ok<AGROW>
            end
        end

        function state = pasting(document, snapshot, parentId, registry, measuredPosition, offset)
            % pasting Check the stored subtree against current destination geometry without inserting it.
            arguments (Input)
                document (1, 1) macd.model.DocumentModel
                snapshot (1, 1) macd.model.SubtreeSnapshot
                parentId (1, 1) string
                registry (1, 1) macd.model.ComponentRegistry
                measuredPosition double {mustBeFinite} = []
                offset (1, 2) double {mustBeFinite} = [10 10]
            end
            arguments (Output)
                state (1, 1) struct
            end
            state = struct("Enabled", false, "Reason", "");
            try
                % Internal references are remapped; external generated references must still exist.
                ids = string({snapshot.Records.Id});
                for record = snapshot.Records
                    for entry = record.Properties
                        if ~isfield(entry.Metadata, "SubtreeReferenceId"), continue, end
                        targetId = string(entry.Metadata.SubtreeReferenceId);
                        if any(ids == targetId), continue, end
                        target = document.getComponent(targetId);
                        if isempty(target) || entry.Path ~= "ContextMenu" || target.Factory ~= "uicontextmenu" || ...
                                target.ParentId ~= document.RootComponentId
                            error("macd:DocumentEditAvailability:Reference", "The stored external component reference is no longer valid.");
                        end
                    end
                end
                macd.model.SubtreePlacementPlanner.prepare(document, snapshot, parentId, registry, ...
                    strings(1, 0), measuredPosition, offset);
                state.Enabled = true;
            catch exception
                state.Reason = string(exception.message);
            end
        end
    end

    methods (Static, Access = private)
        function snapshot = inspect(document, id)
            % inspect Validate complete subtree identities and editable records once per query.
            arguments (Input)
                document (1, 1) macd.model.DocumentModel
                id (1, 1) string
            end
            arguments (Output)
                snapshot (1, 1) macd.model.SubtreeSnapshot
            end
            if id == document.RootComponentId
                error("macd:DocumentEditAvailability:Root", "The document root cannot be moved or deleted.");
            end
            snapshot = macd.model.SubtreeSnapshot(document, id);
            if any(~[snapshot.Records.IsEditable])
                error("macd:DocumentEditAvailability:ReadOnly", "The subtree contains a read-only component.");
            end
        end

        function ownership(document, snapshot, moving)
            % ownership Require identifiable initialization statements without planning replacement source.
            arguments (Input)
                document (1, 1) macd.model.DocumentModel
                snapshot (1, 1) macd.model.SubtreeSnapshot
                moving (1, 1) logical = false
            end
            parsed = snapshot.Records(string({snapshot.Records.Origin}) == "parsed");
            if isempty(parsed), return, end
            analysis = document.sourceAnalysis();
            statements = analysis.Statements;
            [direct, ~] = macd.source.SubtreeReparentSourceEdits.directScope(statements);
            for record = parsed
                spans = record.SourceSpans.Creation;
                if isempty(spans) || isempty(record.SourceSpans.Declaration) || ~record.SourceSpans.Declaration.isKnown()
                    error("macd:DocumentEditAvailability:Ownership", "Creation or declaration ownership is missing.");
                end
                if moving
                    for entry = record.Properties
                        if ~isempty(entry.SourceSpan), spans = [spans entry.SourceSpan]; end %#ok<AGROW>
                    end
                    for setting = record.Settings
                        if ~isempty(setting.Location.SourceSpan), spans = [spans setting.Location.SourceSpan]; end %#ok<AGROW>
                    end
                end
                for span = spans
                    matches = find(arrayfun(@(item) item.Span.StartOffset == span.StartOffset && ...
                        item.Span.EndOffset == span.EndOffset, statements));
                    if ~span.isKnown() || numel(matches) ~= 1 || ~direct(matches)
                        error("macd:DocumentEditAvailability:Ownership", "Initialization ownership is not a unique direct statement.");
                    end
                end
            end
        end
    end
